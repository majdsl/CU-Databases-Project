-- Step 1: the same table on four storage engines.
-- Only the ENGINE= clause differs. Run inside the mariadb client:
--   source /tutorial/01-create-tables.sql

-- MEMORY tables are capped by max_heap_table_size (default 16 MiB).
-- The cap is read when the table is created, so raise it first (64 MiB).
SET SESSION max_heap_table_size = 67108864;

CREATE OR REPLACE TABLE tut_innodb (
  id          INT         NOT NULL,
  airport_id  INT         NOT NULL,
  delay_min   SMALLINT    NOT NULL,
  hits        BIGINT      NOT NULL DEFAULT 0,
  note        VARCHAR(32) NOT NULL,
  PRIMARY KEY (id) USING BTREE,
  KEY by_airport (airport_id) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE OR REPLACE TABLE tut_aria (
  id          INT         NOT NULL,
  airport_id  INT         NOT NULL,
  delay_min   SMALLINT    NOT NULL,
  hits        BIGINT      NOT NULL DEFAULT 0,
  note        VARCHAR(32) NOT NULL,
  PRIMARY KEY (id) USING BTREE,
  KEY by_airport (airport_id) USING BTREE
) ENGINE=Aria DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE OR REPLACE TABLE tut_myisam (
  id          INT         NOT NULL,
  airport_id  INT         NOT NULL,
  delay_min   SMALLINT    NOT NULL,
  hits        BIGINT      NOT NULL DEFAULT 0,
  note        VARCHAR(32) NOT NULL,
  PRIMARY KEY (id) USING BTREE,
  KEY by_airport (airport_id) USING BTREE
) ENGINE=MyISAM DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

-- USING BTREE matters here: MEMORY would otherwise default to HASH indexes
-- (step 4 shows what that changes).
CREATE OR REPLACE TABLE tut_memory (
  id          INT         NOT NULL,
  airport_id  INT         NOT NULL,
  delay_min   SMALLINT    NOT NULL,
  hits        BIGINT      NOT NULL DEFAULT 0,
  note        VARCHAR(32) NOT NULL,
  PRIMARY KEY (id) USING BTREE,
  KEY by_airport (airport_id) USING BTREE
) ENGINE=MEMORY DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

-- 50,000 identical rows per table, generated by MariaDB's built-in SEQUENCE
-- engine (seq_1_to_50000 is a virtual table; nothing is downloaded).
-- The client prints the time each load took.
INSERT INTO tut_innodb (id, airport_id, delay_min, note)
  SELECT seq, 1 + seq % 500, CAST(seq % 196 AS SIGNED) - 15, CONCAT('row-', seq) FROM seq_1_to_50000;
INSERT INTO tut_aria (id, airport_id, delay_min, note)
  SELECT seq, 1 + seq % 500, CAST(seq % 196 AS SIGNED) - 15, CONCAT('row-', seq) FROM seq_1_to_50000;
INSERT INTO tut_myisam (id, airport_id, delay_min, note)
  SELECT seq, 1 + seq % 500, CAST(seq % 196 AS SIGNED) - 15, CONCAT('row-', seq) FROM seq_1_to_50000;
INSERT INTO tut_memory (id, airport_id, delay_min, note)
  SELECT seq, 1 + seq % 500, CAST(seq % 196 AS SIGNED) - 15, CONCAT('row-', seq) FROM seq_1_to_50000;

SELECT 'innodb' AS engine, COUNT(*) AS row_count FROM tut_innodb
UNION ALL SELECT 'aria',   COUNT(*) FROM tut_aria
UNION ALL SELECT 'myisam', COUNT(*) FROM tut_myisam
UNION ALL SELECT 'memory', COUNT(*) FROM tut_memory;
